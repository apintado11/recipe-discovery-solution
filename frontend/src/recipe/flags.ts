export type Flag = {
  code: string;
  color: string;
};

const flags = new Map<string, Flag>();

function add(code: string, color: string, ...names: string[]) {
  const flag: Flag = { code, color };
  for (const name of names) {
    flags.set(name.toLowerCase(), flag);
  }
}

